const placeholders = ["/placeholders/car-1.svg", "/placeholders/car-2.svg", "/placeholders/car-3.svg"];

export const SEED_CARS: Car[] = seedCars.map((seed, i) => {
  const id = `seed-${seed.stockNumber.toLowerCase()}`;
  const title = carTitle(seed);
  return {
    ...seed,
    id,
    slug: carSlug(seed),
    updatedAt: seed.soldAt ?? seed.createdAt,
    images: placeholders.map((_, n) => ({
      id: `${id}-img-${n}`,
      carId: id,
      // Rotate so cards don't all show the same cover.
      storagePath: placeholders[(i + n) % placeholders.length],
      sortOrder: n,
      alt: `${title}, photo ${n + 1}`,
    })),
  };
});
